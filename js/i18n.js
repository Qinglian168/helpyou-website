function t(key) {
    const lang = currentLang;
    return i18nData[lang] && i18nData[lang][key] ? i18nData[lang][key] : key;
}

function applyTranslations() {
    var titleEl = document.querySelector('title[data-i18n]');
    if (titleEl) {
        var key = titleEl.getAttribute('data-i18n');
        var translated = t(key);
        if (translated !== key) {
            titleEl.textContent = translated;
        }
    }

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const translated = t(key);
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
            el.placeholder = translated;
        } else if (el.tagName === 'TITLE') {
            // already handled above
        } else {
            el.textContent = translated;
        }
    });

    // Update placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        const translated = t(key);
        if (translated !== key) {
            el.placeholder = translated;
        }
    });

    if (typeof window.populateProductSelect === 'function') {
        window.populateProductSelect();
    }
}

function initLang() {
    const saved = localStorage.getItem('hy_lang');
    if (saved) {
        currentLang = saved;
    }
    applyTranslations();
}

// Expose to global scope
window.i18nData = i18nData;
window.currentLang = function() { return currentLang; };
window.t = t;
window.setLang = setLang;
window.getLang = getLang;
window.initLang = initLang;
window.applyTranslations = applyTranslations;
